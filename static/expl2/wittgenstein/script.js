function WittgensteinApp() {
  return {
    language: Expl2.getInitialLanguage(),
    match: 72,
    gameIndex: 0,
    criteria: "private",
    ruleStep: 3,
    text() {
      return messages[this.language];
    },
    chooseLanguage(language) {
      this.language = Expl2.setLanguage(language);
      this.renderShared();
    },
    mounted() {
      this.language = Expl2.setLanguage(this.language, { persist: false });
      this.renderShared();
    },
    renderShared() {
      Expl2.applyI18n(messages, { language: this.language });
      Expl2.applyConcepts(concepts, { language: this.language });
      Expl2.setupChapterNavigation({
        label: messages[this.language].tocLabel,
        title: messages[this.language].tocTitle,
      });
    },
    worldItems() {
      return [
        { kind: "circle", style: "left: 18%; top: 30%;" },
        { kind: "square", style: "left: 58%; top: 52%;" },
        { kind: "line", style: "left: 31%; top: 44%; width: 34%; transform: rotate(24deg);" },
      ];
    },
    sentenceItems() {
      const drift = (100 - Number(this.match)) * 0.28;
      return [
        { kind: "circle", style: `left: ${18 + drift}%; top: 30%;` },
        { kind: "square", style: `left: ${58 - drift}%; top: ${52 - drift * 0.35}%;` },
        { kind: "line", style: `left: 31%; top: 44%; width: 34%; transform: rotate(${24 - drift}deg);` },
      ];
    },
    currentGame() {
      return this.text().games[Number(this.gameIndex)] || this.text().games[0];
    },
    criteriaText() {
      return this.text().criteriaTexts[this.criteria];
    },
    ruleNumbers() {
      const numbers = [2, 4, 6, 8, 10];
      return numbers.slice(0, Number(this.ruleStep) + 1);
    },
    ruleInterpretation() {
      return this.text().ruleInterpretations[Number(this.ruleStep) - 1];
    },
  };
}

Expl2.mount({ WittgensteinApp }, "#expl2-app");
